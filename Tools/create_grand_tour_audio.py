"""Original instrumental racing score and layered game effects. No sampled third-party audio."""
from pathlib import Path
import numpy as np
from scipy.signal import butter, sosfilt
from scipy.io.wavfile import write
R=24000
out=Path('Assets/Resources/GrandTour/Audio');out.mkdir(parents=True,exist_ok=True)
rng=np.random.default_rng(42)
def low(x,hz):return sosfilt(butter(2,hz,fs=R,output='sos'),x)
def tone(hz,dur):
 t=np.arange(int(R*dur))/R
 return np.sin(2*np.pi*hz*t)*np.exp(-t*6/dur)
def save(name,data):
 if data.ndim==1:data=np.stack((data,np.roll(data,73)*.85),1)
 data=np.tanh(data*.9);peak=np.max(np.abs(data));data=data/max(1,peak)*.87
 write(out/(name+'.wav'),R,(data*32767).astype(np.int16))
def score(name,bpm,bars,calm=False):
 beat=60/bpm;dur=bars*4*beat;n=int(dur*R);mix=np.zeros((n,2),np.float32)
 def add(signal,at,gain=1,pan=0):
  st=int(at*R);en=min(n,st+len(signal))
  if st>=n:return
  sig=signal[:en-st]*gain;mix[st:en,0]+=sig*(1-pan*.35);mix[st:en,1]+=sig*(1+pan*.35)
 kickT=np.arange(int(.24*R))/R;kick=np.sin(2*np.pi*(46*kickT+14*(1-np.exp(-kickT*35))/35))*np.exp(-kickT*18)
 hatT=np.arange(int(.07*R))/R;hat=(rng.normal(size=len(hatT)))*np.exp(-hatT*75);hat-=low(hat,5000)
 snT=np.arange(int(.16*R))/R;sn=(rng.normal(size=len(snT))*.4+np.sin(snT*2*np.pi*185)*.3)*np.exp(-snT*20)
 roots=[41.203,48.999,36.708,43.654]
 for bar in range(bars):
  root=roots[(bar//4)%4];phase=bar%16
  for step in range(8):
   at=(bar*4+step*.5)*beat
   if not calm or step%2==0:add(kick,at,.7 if step%2==0 else .25)
   add(hat,at,.12 if step%2 else .07,.6 if step%2 else -.6)
   if step in (2,6):add(sn,at,.35 if not calm else .14)
   length=beat*.44;t=np.arange(int(length*R))/R;freq=root*(2 if step in (3,7) else 1)
   bass=(np.sin(2*np.pi*freq*t)+.25*np.sin(2*np.pi*freq*2*t)+.12*np.sin(2*np.pi*freq*3*t))*np.minimum(t/.008,1)*np.exp(-t*7)
   add(bass,at,.48)
   if phase>=4 or calm:
    sem=[0,7,12,10,7,3,14,12][step];f=root*4*2**(sem/12)
    lead=tone(f,beat*.7)+.25*tone(f*2,beat*.7)
    add(lead,at,.13 if not calm else .09,np.sin(step*1.7))
    add(lead,at+beat*.75,.045,-np.sin(step*1.7))
  t=np.arange(int(beat*4*R))/R
  chord=sum(np.sin(2*np.pi*root*2*2**(k/12)*t+.2*np.sin(t*2)) for k in [0,3,7])/3
  env=np.minimum(t/.3,1)*np.minimum((beat*4-t)/.5,1)
  add(chord*env,bar*4*beat,.12 if calm else .07,-.2)
 # A restrained seamless loop seam, rather than an abrupt full-level waveform discontinuity.
 fade=int(.02*R);mix[:fade]*=np.linspace(0,1,fade)[:,None];mix[-fade:]*=np.linspace(1,0,fade)[:,None]
 save(name,mix)
score('RaceScore',142,32)
score('MenuScore',112,16,True)
for name,hz,dur in [('UI',880,.08),('Coin',1320,.35),('Fuel',520,.5),('Jump',650,.3),('Finish',660,1.2)]:
 t=np.arange(int(R*dur))/R;signal=sum(tone(hz*ratio,dur)*amp for ratio,amp in [(1,.5),(1.5,.2),(2,.1)])
 save(name,signal)
t=np.arange(R)/R;noise=rng.normal(size=R)
save('Impact',(low(noise,1800)*.6+np.sin(t*2*np.pi*68)*.6)*np.exp(-t*15))
save('Crash',(low(noise,2800)*.6+np.sin(t*2*np.pi*(78*t+15))*.4)*np.exp(-t*5))
save('Boost',(low(noise,1800)*.25+np.sin(2*np.pi*(180*t+300*t*t))*.15)*np.sin(np.pi*t)**2)
save('Pass',low(noise,1200)*np.sin(np.pi*t)**4*.5)
t=np.arange(R*3)/R;air=low(rng.normal(size=len(t)),5000);air-=low(air,250);save('Wind',air*.16)
t=np.arange(R*2)/R
motor=sum(np.sin(2*np.pi*60*k*t+np.sin(t*2*np.pi*30)*.13)/k for k in range(1,11))
save('Engine',motor*.2+low(rng.normal(size=len(t)),1800)*.035)
(out/'PROVENANCE.txt').write_text('Original authored electronic score and procedural sound design generated by Tools/create_grand_tour_audio.py. Stereo PCM 24 kHz; no third-party samples. Race: 142 BPM / 32 bars. Menu: 112 BPM / 16 bars.\n')
print('Wrote original scores and 10 effects/loops')
